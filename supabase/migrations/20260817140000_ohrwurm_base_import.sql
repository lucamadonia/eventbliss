-- OHRWURM — die 1281 Basissongs in die Tabelle importieren.
--
-- Bisher lagen sie ausschließlich als gepackter String im Code
-- (ohrwurm-content.ts). Dadurch waren sie im Adminbereich unsichtbar und
-- einzelne Songs ließen sich nicht abschalten — genau das braucht es aber, um
-- die Marktrelevanz pro Song zu korrigieren.
--
-- `base_id` verknüpft eine Zeile mit dem statischen Song (ow-0001 …). Sobald
-- die Tabelle befüllt ist, ERSETZEN diese Zeilen die statische Liste im Spiel;
-- der Code bleibt nur noch Offline-Fallback. Ohne diese Ersetzung stünde jeder
-- Song doppelt im Stapel.
--
-- `language = '*'` heißt „gilt für alle Sprachfassungen". Die grobe
-- Marktabgrenzung passiert weiterhin über das Herkunftsland im Code, die feine
-- über den is_active-Schalter hier.

ALTER TABLE public.ohrwurm_songs
  ADD COLUMN IF NOT EXISTS base_id text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'ohrwurm_songs_base_id_key'
  ) THEN
    ALTER TABLE public.ohrwurm_songs
      ADD CONSTRAINT ohrwurm_songs_base_id_key UNIQUE (base_id);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_ohrwurm_songs_base
  ON public.ohrwurm_songs (base_id) WHERE base_id IS NOT NULL;

-- Admins müssen auch INAKTIVE Songs sehen, sonst ließe sich ein abgeschalteter
-- Song nie wieder einschalten. Die bestehende Lese-Policy deckt nur
-- is_active = true ab.
DROP POLICY IF EXISTS "Admins read all ohrwurm songs" ON public.ohrwurm_songs;
CREATE POLICY "Admins read all ohrwurm songs"
  ON public.ohrwurm_songs FOR SELECT
  USING (EXISTS (SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role = 'admin'));

